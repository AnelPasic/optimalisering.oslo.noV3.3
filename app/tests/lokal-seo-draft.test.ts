import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import YAML from 'yaml';
import {pageSchema} from '../src/lib/content-schema.ts';
import {cmsJsonSave,entryForFile,assertPreservedContent} from './helpers/pages-cms-json.ts';
test('Lokal SEO is an editor-ready service draft outside the published collection',()=>{
 const file='src/content/drafts/lokal-seo.json';
 const draft=JSON.parse(readFileSync(file,'utf8'));
 assert.equal(draft.slug,'lokal-seo');assert.equal(draft.kind,'service');
 assert.equal(draft.status,'REVIEW_REQUIRED');assert.equal(draft.authority,'DRAFT / NON-AUTHORITATIVE');
 assert.equal(pageSchema.safeParse(draft).success,true);
 const cms=YAML.parse(readFileSync('../.pages.yml','utf8'));
 const entry=entryForFile(cms,'app/'+file);assert.equal(entry?.type,'file');
 const edited=structuredClone(draft);edited.sections[0].body.push('Kun CMS-fixture.');
 const saved=JSON.parse(cmsJsonSave(draft,edited,entry,cms));
 assertPreservedContent(edited,saved);assert.deepEqual(pageSchema.parse(saved),pageSchema.parse(edited));
 const loader=readFileSync('src/content.config.ts','utf8');assert.ok(loader.includes("base: './src/content/pages'"));
 const home=JSON.parse(readFileSync('src/content/pages/home.json','utf8'));
 assert.equal(JSON.stringify(home).includes('"href":"/lokal-seo/"'),false);
});
