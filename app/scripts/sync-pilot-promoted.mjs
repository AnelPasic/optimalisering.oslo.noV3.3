import {readFileSync,readdirSync,writeFileSync,existsSync} from 'node:fs';
import {resolve,join} from 'node:path';
const base=resolve(new URL('../',import.meta.url).pathname);
const root=resolve(base,'..');
const folder=resolve(base,'src/content/global-promoted');
const yamlFile=resolve(root,'.pages.yml'),outputFile=resolve(base,'src/lib/promoted-global.generated.ts');
const restricted=new Set(['behov','regneeksempel','sjekk','priser','resultater','mekanisme','passer','sporsmal']);
const opts=(existsSync(folder)?readdirSync(folder).filter(name=>name.endsWith('.json')):[]).sort();
const values=opts.map(file=>{
 const id=file.slice(0,-5),entry=JSON.parse(readFileSync(join(folder,file),'utf8'));
 if(!/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(id)||restricted.has(id)||entry.id!==id||entry._block!=='content'||typeof entry.name!=='string'||!entry.name.trim()||!entry.heading?.trim()||!Array.isArray(entry.body)||!entry.body.every(x=>typeof x==='string')||entry.visibility!==undefined)throw new Error('Invalid promoted global master: '+file);
 return {id,label:entry.name};
});
const imports=values.map((x,i)=>'import global'+i+" from '../content/global-promoted/"+x.id+".json' with { type: 'json' };").join('\n');
const moduleSource='// Auto-generated by app/scripts/sync-pilot-promoted.mjs. Do not edit.\n'+(imports?imports+'\n':'')+'export const promotedGlobalMasters: Readonly<Record<string, unknown>> = {'+(values.length?'\n'+values.map((x,i)=>'  '+JSON.stringify(x.id)+': global'+i+',').join('\n')+'\n':'')+'};\n';
let y=readFileSync(yamlFile,'utf8');
for(const [n,pad] of [[1,20],[2,12],[3,12]]){
 const start='# PILOT_PROMOTED_CHOICES_'+n+'_BEGIN', end='# PILOT_PROMOTED_CHOICES_'+n+'_END';
 if(y.split(start).length!==2||y.split(end).length!==2)throw new Error('Missing promoted choices markers: '+n);
 const lines=values.map(v=>' '.repeat(pad)+'- name: '+JSON.stringify(v.id)+'\n'+' '.repeat(pad+2)+'label: '+JSON.stringify(v.label)).join('\n');
 const startAt=y.indexOf(start)+start.length,endAt=y.indexOf(end);
 y=y.slice(0,startAt)+'\n'+(lines?lines+'\n':'')+y.slice(endAt);
}
if(process.argv.includes('--write')){
 if(readFileSync(outputFile,'utf8')!==moduleSource)writeFileSync(outputFile,moduleSource);
 if(readFileSync(yamlFile,'utf8')!==y)writeFileSync(yamlFile,y);
 console.log('Synced '+values.length+' promoted global CMS masters');
}else{
 if(readFileSync(outputFile,'utf8')!==moduleSource||readFileSync(yamlFile,'utf8')!==y){console.error('Generated global catalog stale; run node app/scripts/sync-pilot-promoted.mjs --write');process.exitCode=1;}
 else console.log('Promoted global CMS catalog current: '+values.length);
}
