import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';

// Single source of truth is the Pages CMS appearance JSON. There is no
// independently configured Cloudflare/dashboard noindex switch.
const TECHNICAL_ROUTES='/404.html\n  X-Robots-Tag: noindex, nofollow\n/design-system/*\n  X-Robots-Tag: noindex, nofollow\n';
export function getNoindex(data){
 if(data.searchEngineNoindex===undefined)return true; // older content remains safely hidden
 if(typeof data.searchEngineNoindex!=='boolean')throw Error('CMS searchEngineNoindex must be boolean');
 return data.searchEngineNoindex;
}
export function renderHeaders(noindex){
 if(typeof noindex!=='boolean')throw Error('Expected boolean noindex');
 // Same CMS choice controls HTML and HTTP response headers.
 return '# Generated by npm run build from Pages CMS; do not edit deployment headers manually.\n'
   +(noindex?'/*\n  X-Robots-Tag: noindex, nofollow\n':'')
   +TECHNICAL_ROUTES;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href){
 const data=JSON.parse(readFileSync('src/content/site-chrome/appearance.json','utf8'));
 const noindex=getNoindex(data);
 writeFileSync('dist/_headers',renderHeaders(noindex));
 if(noindex)console.warn('[LAUNCH CHECK] noindex PÅ i Pages CMS: nettstedet vil være skjult for søkemotorer, også på produksjonsdomenet.');
 else console.warn('[LAUNCH CHECK] noindex AV i Pages CMS: alle vanlige domener/preview kan nå indekseres. Slå av kun ved godkjent lansering; ikke bruk Cloudflare som en separat noindex-bryter.');
}
